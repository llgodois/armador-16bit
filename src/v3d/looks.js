export const SKIN = { a: '#f2d2b6', b: '#e8b98f', c: '#d29a6a', d: '#b97a4a', e: '#93582f', f: '#6e4223', g: '#4e2d17' };
export const HAIR = { k: '#141414', n: '#3b2414', b: '#6b3e1f', y: '#d8b56a', r: '#b5532a', v: '#3fbf5a' };

const cache = new Map();
// { skin, hairStyle, hairColor, beard, headband, bulk } ou null
export function lookOf(name) {
  if (!name) return null;
  if (cache.has(name)) return cache.get(name);
  const alt = String(name).replace(/[.’']/g, '');
  const ALIAS = { 'Alexandre Sarr': 'Alex Sarr', 'Nicolas Claxton': 'Nic Claxton', 'Cameron Johnson': 'Cam Johnson' };
  const raw = RAW[name] || RAW[alt] || RAW[ALIAS[name]] || RAW[alt.replace(/ (Jr|Sr|II|III|IV)$/, '')];
  let out = null;
  if (raw) {
    const [s, style, color, beard, ...flags] = raw.split(' ');
    out = {
      skin: SKIN[s] || SKIN.e,
      hairStyle: style,
      hairColor: HAIR[color] || HAIR.k,
      beard: Number(beard) || 0,
      headband: flags.includes('h'),
      bulk: flags.includes('B'),
    };
  }
  cache.set(name, out);
  return out;
}
