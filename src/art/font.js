const CELL_W = 6;
const CELL_H = 8;
const CHARS = Object.keys(GLYPHS).join('');
const PER_ROW = 16;

export function generateFont(scene) {
  const rows = Math.ceil(CHARS.length / PER_ROW);
  if (scene.textures.exists('font')) scene.textures.remove('font');
  const tex = scene.textures.createCanvas('font', PER_ROW * CELL_W, rows * CELL_H);
  const ctx = tex.getContext();
  ctx.fillStyle = '#ffffff';
  [...CHARS].forEach((ch, i) => {
    const gx = (i % PER_ROW) * CELL_W;
    const gy = Math.floor(i / PER_ROW) * CELL_H;
    GLYPHS[ch].forEach((bits, y) => {
      for (let x = 0; x < 5; x++) if (bits & (1 << (4 - x))) ctx.fillRect(gx + x, gy + y, 1, 1);
    });
  });
  tex.refresh();

  scene.cache.bitmapFont.add(
    'pixel',
    Phaser.GameObjects.RetroFont.Parse(scene, {
      image: 'font',
      width: CELL_W,
      height: CELL_H,
      chars: CHARS,
      charsPerRow: PER_ROW,
      spacing: { x: 0, y: 0 },
      offset: { x: 0, y: 0 },
      lineSpacing: 2,
    }),
  );
}

// Converte qualquer texto para o que a fonte sabe desenhar.
export function toFontText(s) {
  return String(s)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase();
}
